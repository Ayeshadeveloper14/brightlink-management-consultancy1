/**
 * Robust translation helper with automatic normalization
 */
export const translateToArabic = (text) => {
  if (!text || typeof text !== 'string') return text;
  const trimmed = text.trim();
  if (!trimmed) return text;

  // Direct exact match
  if (ARABIC_DICTIONARY[trimmed]) return ARABIC_DICTIONARY[trimmed];

  // Strip trailing colon
  if (trimmed.endsWith(':')) {
    const core = trimmed.slice(0, -1).trim();
    if (ARABIC_DICTIONARY[core]) return ARABIC_DICTIONARY[core] + ':';
  }

  // Strip trailing asterisk or space + asterisk
  if (trimmed.endsWith('*')) {
    const core = trimmed.replace(/\s*\*+$/, '').trim();
    if (ARABIC_DICTIONARY[core]) return ARABIC_DICTIONARY[core] + ' *';
  }

  // Strip question mark
  if (trimmed.endsWith('?')) {
    const core = trimmed.slice(0, -1).trim();
    if (ARABIC_DICTIONARY[core]) return ARABIC_DICTIONARY[core] + '؟';
  }

  // Strip quotation marks
  if ((trimmed.startsWith('"') && trimmed.endsWith('"')) || (trimmed.startsWith('“') && trimmed.endsWith('”'))) {
    const core = trimmed.slice(1, -1).trim();
    if (ARABIC_DICTIONARY[core]) return '«' + ARABIC_DICTIONARY[core] + '»';
  }

  return text;
};
