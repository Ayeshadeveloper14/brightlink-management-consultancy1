const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
  const [currentLang, setCurrentLang] = useState(() => {
    try {
      const saved = localStorage.getItem('brightlink_language');
      const found = LANGUAGES.find(l => l.code === saved);
      return found ? found.code : 'en';
    } catch {
      return 'en';
    }
  });

  const languageConfig = LANGUAGES.find(l => l.code === currentLang) || LANGUAGES[0];
  const isRTL = languageConfig.dir === 'rtl';

  useEffect(() => {
    try {
      localStorage.setItem('brightlink_language', currentLang);
    } catch {}

    // Update document HTML direction and lang attribute
    document.documentElement.dir = languageConfig.dir;
    document.documentElement.lang = currentLang;

    // Optional body class for styling adjustments if needed
    if (isRTL) {
      document.body.classList.add('rtl-layout');
    } else {
      document.body.classList.remove('rtl-layout');
    }
  }, [currentLang, languageConfig, isRTL]);

  const setLanguage = (code) => {
    const valid = LANGUAGES.some(l => l.code === code);
    if (valid) {
      setCurrentLang(code);
    }
  };

  const t = (key, fallback = '') => {
    const langDict = TRANSLATIONS[currentLang];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to English
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return fallback || key;
  };

  const tItem = (title) => {
    if (!title) return '';
    if (currentLang === 'en') return title;
    const itemDict = ITEM_TRANSLATIONS[title];
    if (itemDict && itemDict[currentLang]) {
      return itemDict[currentLang];
    }
    return title;
  };

  return (
    <LanguageContext.Provider
      value={{
        currentLanguage: currentLang,
        languageConfig,
        languages: LANGUAGES,
        setLanguage,
        isRTL,
        dir: languageConfig.dir,
        t,
        tItem
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

