export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    // Return sensible fallback if used outside provider
    return {
      currentLanguage: 'en',
      languageConfig: LANGUAGES[0],
      languages: LANGUAGES,
      setLanguage: () => {},
      isRTL: false,
      dir: 'ltr',
      t: (key, fallback = '') => fallback || key
    };
  }
  return context;
};

